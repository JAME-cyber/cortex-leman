def test_crc_validation_catches_corruption():
    wm = ChainMarkWatermarker()
    result = wm.watermark("A response with enough words for a machine-readable watermark.", visible=False)
    zero_width_positions = [i for i, c in enumerate(result.text) if c in ("\u200b", "\u200c")]
    assert zero_width_positions
    # Corrupt a bit AFTER the magic prefix (position >= 16 bits) so the magic
    # is still found but the CRC check fails.
    # Each zero-width char = 1 bit. Magic = 16 bits. Corrupt at least 1 bit after offset 16.
    index = zero_width_positions[min(20, len(zero_width_positions) - 1)]
    corrupted_char = "\u200c" if result.text[index] == "\u200b" else "\u200b"
    corrupted = result.text[:index] + corrupted_char + result.text[index + 1:]
    detection = wm.detect(corrupted)
    assert detection.is_watermarked
    assert not detection.watermark_valid
